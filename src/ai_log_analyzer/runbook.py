"""Runbook generator — turn a finding into a copy-pasteable Ansible playbook
or Python+netmiko script. Inspired by NetBrain's runbook conversion.
"""
from __future__ import annotations

import re
from textwrap import indent
from typing import Any

import yaml

from ai_log_analyzer.remediation import clean_text


def _safe(name: str) -> str:
    return "".join(c if (c.isalnum() or c in "-_") else "_" for c in name)


class _Scalar(str):
    """A YAML scalar that needs more than the default style: `!unsafe` and/or a literal block."""

    unsafe = False
    block = False


# Characters PyYAML can write raw without a YAML loader turning them into something else. The
# Unicode line breaks (NEL, LS, PS), BOM, tabs and control characters are not among them: those
# scalars are forced into the double-quoted style, which escapes them.
_PLAIN_TEXT_RE = re.compile(r"[\x20-\x7e\xa0-\u2027\u202a-\ufefe\uff00-\ufffd]*")


def _scalar(value: Any, block: bool = False) -> str:
    """Model- or log-derived text for the playbook. Anything with a brace is tagged `!unsafe` so Ansible
    on the controller never renders it as Jinja; the YAML emitter quotes it, nothing is pasted into YAML."""
    text = str(value)
    unsafe = "{" in text or "}" in text
    lines = text.split("\n")
    plain = all(_PLAIN_TEXT_RE.fullmatch(line) for line in lines)
    if plain and not unsafe and not (block and len(lines) > 1):
        return text
    out = _Scalar(text)
    out.unsafe, out.block = unsafe, block and len(lines) > 1 and plain
    return out


class _PlaybookDumper(yaml.SafeDumper):
    def increase_indent(self, flow: bool = False, indentless: bool = False) -> Any:
        return super().increase_indent(flow, False)  # list items indented under their key, as before


def _represent_scalar(dumper: yaml.SafeDumper, data: _Scalar) -> Any:
    tag = "!unsafe" if data.unsafe else "tag:yaml.org,2002:str"
    return dumper.represent_scalar(tag, str(data), style="|" if data.block else '"')


_PlaybookDumper.add_representer(_Scalar, _represent_scalar)


def _doc_text(value: Any, limit: int = 500) -> str:
    """One line of text that cannot end or alter a triple-quoted, non-raw Python docstring."""
    return clean_text(value, limit).replace("\\", "\\\\").replace('"', '\\"')


def to_ansible_playbook(
    finding: dict,
    hostnames: list[str],
    platform_hint: str = "junos",
) -> str:
    """Generate an Ansible playbook that applies the finding's patches.

    The playbook is emitted by a YAML dumper, never by string formatting, and every model- or
    log-derived value is a quoted scalar (`!unsafe` when it holds a brace) so it stays literal text
    on the controller: no Jinja, no extra plays. The `#` header is one cleaned line per field.
    """
    title = str(finding.get("title", "remediation"))
    severity = str(finding.get("severity", "medium"))
    rationale = finding.get("rationale") or finding.get("root_cause") or ""

    # Pull a flat list of CLI commands from the finding
    cmds = _extract_cmds(finding, platform_hint)
    if not cmds:
        cmds = ["# No platform-specific commands found in the finding"]

    names = [str(h) for h in hostnames] if isinstance(hostnames, (list, tuple)) else []
    hosts_block = ", ".join(names) or "all"
    if platform_hint.lower() == "frr":
        module, body = "ansible.builtin.shell", _scalar("\n".join(cmds), block=True)
    elif platform_hint.lower() == "eos":
        module, body = "arista.eos.eos_config", {"lines": [_scalar(c) for c in cmds]}
    else:  # junos
        module, body = "junipernetworks.junos.junos_config", {"lines": [_scalar(c) for c in cmds]}

    play = {
        "name": _scalar(f"Remediate: {title[:60]}"),
        "hosts": _scalar(hosts_block),
        "gather_facts": False,
        "serial": 1,
        "tasks": [
            {"name": _scalar(f"Apply patch ({platform_hint})"), module: body, "register": "result"},
            {"name": "Show diff", "ansible.builtin.debug": {"var": "result"}},
        ],
    }
    header = (
        "---\n"
        "# Auto-generated by AI Log Analyzer\n"
        f"# Finding:  [{clean_text(severity, 40).upper()}] {clean_text(title, 200)}\n"
        f"# Why:      {clean_text(rationale, 140)}\n"
        f"# Targets:  {clean_text(hosts_block, 200)}\n"
    )
    return header + yaml.dump([play], Dumper=_PlaybookDumper, sort_keys=False, default_flow_style=False,
                              allow_unicode=True, width=1_000_000)


def to_netmiko_script(
    finding: dict,
    hostnames: list[str],
    platform_hint: str = "junos",
) -> str:
    """Generate a Python + netmiko script.

    Finding and request text only ever reaches the script as a string: the docstring gets a
    one-line, escaped copy, and the commands and device names go through `repr()`.
    """
    title = finding.get("title", "remediation")
    severity = finding.get("severity", "medium")
    names = [str(h) for h in hostnames] if isinstance(hostnames, (list, tuple)) else []
    cmds = _extract_cmds(finding, platform_hint)
    if not cmds:
        cmds = ["# No platform-specific commands found"]

    device_type = {"junos": "juniper_junos", "eos": "arista_eos",
                   "frr": "linux"}.get(platform_hint.lower(), "linux")

    return f"""#!/usr/bin/env python3
\"\"\"Auto-generated by AI Log Analyzer.

Finding: [{_doc_text(severity, 40).upper()}] {_doc_text(title)}
Targets: {_doc_text(', '.join(names)) or '<edit DEVICES list>'}
\"\"\"
import os
import sys
from netmiko import ConnectHandler

DEVICES = {names or ['device-name-here']!r}
USERNAME = os.environ.get("NET_USER") or "admin"
PASSWORD = os.environ.get("NET_PASS")  # never hardcode

COMMANDS = [
{indent(chr(10).join(repr(c) + ',' for c in cmds), '    ')}
]


def remediate(host: str) -> None:
    conn = ConnectHandler(
        device_type={device_type!r},
        host=host,
        username=USERNAME,
        password=PASSWORD,
        timeout=30,
    )
    print(f"[{{host}}] applying {{len(COMMANDS)}} command(s)…")
    output = conn.send_config_set(COMMANDS)
    print(output)
    # Junos / Arista commits handled by send_config_set in most netmiko versions;
    # add explicit commit if your driver needs it.
    conn.disconnect()


def main() -> None:
    for host in DEVICES:
        try:
            remediate(host)
        except Exception as e:
            print(f"[{{host}}] ERROR: {{e}}", file=sys.stderr)


if __name__ == "__main__":
    main()
"""


def _extract_cmds(finding: dict, platform_hint: str) -> list[str]:
    """Extract platform-specific CLI commands from a finding's deep_analysis or fix_per_device."""
    plat = platform_hint.lower()
    out: list[str] = []

    # Site-level finding shape: fix_per_device: {hostname: [cmds]}
    fpd = finding.get("fix_per_device") or {}
    if fpd:
        for cmds in fpd.values():
            if isinstance(cmds, list):
                out.extend(cmds)

    # Single-device finding shape: patch: [cmds]
    patch = finding.get("patch") or []
    if isinstance(patch, list):
        out.extend(patch)

    # Phased deep_analysis (action items)
    deep = finding.get("deep_analysis") or {}
    if deep:
        for phase in deep.get("phases") or []:
            for action in phase.get("actions") or []:
                cli = action.get("cli") or {}
                if isinstance(cli, dict):
                    if plat in cli:
                        out.append(cli[plat])
                    elif "any" in cli:
                        out.append(cli["any"])

    # De-dup while preserving order
    seen: set[str] = set()
    uniq: list[str] = []
    for c in out:
        c = c.strip() if isinstance(c, str) else ""
        if c and c not in seen:
            seen.add(c)
            uniq.append(c)
    return uniq
